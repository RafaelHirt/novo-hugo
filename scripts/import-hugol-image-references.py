for base, rows in source['bases'].items():
    report.extend([f"## {'Novo Prédio' if base == 'new' else 'Base HUGOL sem aumento'}", '',
                   '| Grupo / serviço | Célula do preço | Dashboard | P verde / imagem | Item da imagem / vínculo de preço | Conferência |',
                   '| --- | --- | ---: | --- | --- | --- |'])
    for row in rows:
        item = row['priceReference']
        listed = 'unit' in item
        status = 'Sem referência na imagem' if not listed else 'Confere' if cents(row['unit']) == cents(item['unit']) else 'Divergente'
        report.append(f"| {row['group']} · {row['name']} | {row['sourceUnitCell']} | {money(row['unit'])} | "
                      + (f"{item['percentile']} · {money(item['unit'])}" if listed else '—')
                      + f" | {item.get('items', '—')}"
                      + (f"; `{row['sourceUnitCell']}{item['linkedPriceFormula']}`" if item.get('linkedPriceFormula') else '')
                      + f" | {status} |")
    report.append('')
(root / 'docs/hugol-percentis-conferencia.md').write_text('\n'.join(report))
