"""Compare the user-provided HUGOL image prices against the existing source.

Usage: python scripts/import-hugol-image-references.py /path/to/financial-workbook.xlsx
Mappings are explicit by service; price equality never determines a percentile.
Financial fields are kept unchanged. External SADT links are checked in the workbook.
"""
import argparse
import hashlib
import json
import re
from collections import Counter
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import openpyxl

parser = argparse.ArgumentParser()
parser.add_argument('workbook')
args = parser.parse_args()
workbook = Path(args.workbook)
root = Path(__file__).resolve().parents[1]
transcription = Path(__file__).with_name('hugol-image-reference.json')
reference = json.loads(transcription.read_text())
target = root / 'hugol-source.js'
source = json.loads(target.read_text().split('export const hugolSource = ', 1)[1].strip().removesuffix(';'))
assert hashlib.sha256(workbook.read_bytes()).hexdigest() == source['sha256']
values = openpyxl.load_workbook(workbook, data_only=True)
formulas = openpyxl.load_workbook(workbook, data_only=False)


def cents(value):
    return int(Decimal(str(value)).quantize(Decimal('.01'), rounding=ROUND_HALF_UP) * 100)


audit = {}
for base, rows in source['bases'].items():
    sheet_name = next(item['sourceSheet'] for item in source['presets'] if item['base'] == base)
    column = 'H' if base == 'same' else 'M'
    counts = Counter()
    for row in rows:
        cell = f"{column}{row['sourceRow']}"
        assert cents(values[sheet_name][cell].value) == cents(row['unit']), row['id']
        key = reference['mappings'][base][str(row['sourceRow'])]
        entry = reference['catalog'].get(key) if key else None
        image = dict(source='HUGOL image', items=entry['items'], service=entry['service'], percentile=entry['percentile'], unit=entry['unit']) if entry else dict(source='HUGOL image')
        if entry and row['group'] == 'SADT externo':
            formula = formulas[sheet_name][cell].value
            match = re.fullmatch(rf'={column}(\d+)', formula or '')
            assert match, (sheet_name, cell, formula)
            linked = next(item for item in rows if item['sourceRow'] == int(match[1]))
            assert linked['group'] == 'SADT interno'
            assert reference['mappings'][base][str(linked['sourceRow'])] == key
            image['linkedPriceFormula'] = formula
        status = 'not_listed' if not entry else 'match' if cents(row['unit']) == cents(entry['unit']) else 'different'
        counts[status] += 1
        row.update(priceReference=image, unitBasis=entry['percentile'] if status == 'match' else None,
                   unitReference=f"Ref. HUGOL: {entry['percentile']}" if status == 'match' else 'Diverge da referência HUGOL' if entry else 'Sem referência na imagem',
                   sourceUnitCell=cell)
    audit[base] = dict(counts)

source['imageReference'] = dict(source=reference['source'], selection=reference['selection'], imageTotals=reference['imageTotals'],
                              transcriptionSha256=hashlib.sha256(transcription.read_bytes()).hexdigest(), audit=audit)
target.write_text('// Approved worksheet values and incremental changes. Generated by scripts/import-hugol.py.\n'
                  '// User-provided HUGOL image references checked by scripts/import-hugol-image-references.py.\n'
                  'export const hugolSource = ' + json.dumps(source, ensure_ascii=False, indent=2) + ';\n')
print(json.dumps(audit, ensure_ascii=False))


def money(value):
    return 'R$ ' + f'{value:,.2f}'.replace(',', '_').replace('.', ',').replace('_', '.')


