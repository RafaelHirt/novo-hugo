"""Annotate the HUGO increment source with the selected contract percentiles.

Usage: python scripts/import-hugo-percentiles.py /path/to/correct-workbook.xlsx
Only reference metadata is changed; quantities, prices and totals are preserved.
"""
import argparse
import hashlib
import json
import re
import unicodedata
from collections import Counter
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import openpyxl

parser = argparse.ArgumentParser()
parser.add_argument('workbook')
args = parser.parse_args()
path = Path(args.workbook)
values = openpyxl.load_workbook(path, data_only=True)
formulas = openpyxl.load_workbook(path, data_only=False)
sheet = values['HUGO - ATUAL']
assert [sheet[f'{column}3'].value for column in 'KLM'] == ['P25', 'P50', 'P75']
groups = [(6, 10, 'Enfermarias'), (13, 17, 'UTI'), (22, 22, 'Emergência'),
          (25, 25, 'Hospital dia'), (28, 30, 'Atendimento ambulatorial'),
          (34, 35, 'Cirurgias'), (39, 57, 'SADT interno'),
          (61, 65, 'SADT externo'), (69, 69, 'Escritório de gestão de altas')]


def cents(value):
    return int(Decimal(str(value)).quantize(Decimal('.01'), rounding=ROUND_HALF_UP) * 100)


def normalized(value):
    return ''.join(c for c in unicodedata.normalize('NFD', value.lower()) if c.isalnum())


origins = []
for first, last, group in groups:
    for index in range(first, last + 1):
        formula = formulas[sheet.title][f'O{index}'].value
        match = re.fullmatch(r'=([KLM]\d+)', formula)
        assert match, (index, formula)
        cell = match[1]
        assert cents(sheet[cell].value) == cents(sheet[f'O{index}'].value)
        merged = any(cell in area and area.min_col < area.max_col for area in sheet.merged_cells.ranges)
        basis = None if merged else {'K': 'P25', 'L': 'P50', 'M': 'P75'}[cell[0]]
        origins.append(dict(group=group, name=str(sheet[f'C{index}'].value).strip(),
                            unit=cents(sheet[cell].value), basis=basis, cell=cell))

target = Path(__file__).resolve().parents[1] / 'hugo-source.js'
source = json.loads(target.read_text().split('export const hugoSource = ', 1)[1].strip().removesuffix(';'))
before = {row['id']: dict(row) for row in source['bases']['new']}
contract_rows = []
for row in source['bases']['new']:
    # The new-building price must still be the current dashboard price.
    assert cents(values['HUGO - SEM BANCO DE SANGUE'][f"M{row['sourceRow']}"].value) == cents(row['unit']), row['id']
    family = lambda group: 'SADT' if group.startswith('SADT') else group
    candidates = [item for item in origins if family(item['group']) == family(row['group']) and item['unit'] == cents(row['unit'])]
    exact = [item for item in candidates if normalized(item['name']) == normalized(row['name']) and item['group'] == row['group']]
    candidates = exact or candidates
    bases = {item['basis'] for item in candidates}
    if len(bases) > 1:
        raise ValueError(f'Ambiguous percentile for {row["id"]}: {candidates}')
    basis = next(iter(bases), None)
    row.update(unitBasis=basis, unitReference=f'Referência: {basis}' if basis else 'Valor contratual',
               sourceUnitCell=f"M{row['sourceRow']}", sourcePercentileSheet=sheet.title,
               sourcePercentileCells=sorted({item['cell'] for item in candidates}))
    if not basis:
        contract_rows.append(row['id'])
    for field, value in before[row['id']].items():
        if field not in {'unitBasis', 'unitReference', 'sourceUnitCell', 'sourcePercentileSheet', 'sourcePercentileCells'}:
            assert row[field] == value

source['percentileReference'] = dict(fileName=path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                                   sourceSheet=sheet.title, contractRows=contract_rows)
target.write_text('// Approved worksheet values and incremental changes. Generated by scripts/import-hugol.py.\n'
                  '// Percentile references enriched by scripts/import-hugo-percentiles.py.\n'
                  'export const hugoSource = ' + json.dumps(source, ensure_ascii=False, indent=2) + ';\n')
print('HUGO percentile references:', dict(Counter(row['unitBasis'] or 'Valor contratual' for row in source['bases']['new'])))
