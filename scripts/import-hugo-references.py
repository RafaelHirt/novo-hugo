"""Identify the contract price source without inferring percentiles.

Usage: python scripts/import-hugo-references.py /path/to/correct-workbook.xlsx
Only reference metadata changes. Never match prices from another worksheet to P.
"""
import argparse
import hashlib
import json
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import openpyxl

parser = argparse.ArgumentParser()
parser.add_argument('workbook')
args = parser.parse_args()
path = Path(args.workbook)
values = openpyxl.load_workbook(path, data_only=True)
target = Path(__file__).resolve().parents[1] / 'hugo-source.js'
source = json.loads(target.read_text().split('export const hugoSource = ', 1)[1].strip().removesuffix(';'))
sheets = [preset['sourceSheet'] for preset in source['presets']]


def cents(value):
    return int(Decimal(str(value)).quantize(Decimal('.01'), rounding=ROUND_HALF_UP) * 100)


for name in sheets:
    sheet = values[name]
    assert str(sheet['M3'].value).strip() == 'Valor Contrato'
    assert str(sheet['M4'].value).strip() == 'HUGO'
    for row in source['bases']['new']:
        assert cents(sheet[f"M{row['sourceRow']}"].value) == cents(row['unit']), (name, row['id'])

for row in source['bases']['new']:
    row.update(unitBasis=None, unitReference='Valor contratual', sourceUnitCell=f"M{row['sourceRow']}")
    row.pop('sourcePercentileSheet', None)
    row.pop('sourcePercentileCells', None)

source.pop('percentileReference', None)
source['contractReference'] = dict(fileName=path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                                 sourceSheets=sheets, priceColumn='M', priceHeader='Valor Contrato HUGO')
target.write_text('// Approved worksheet values and incremental changes. Generated by scripts/import-hugol.py.\n'
                  '// Contract references recorded by scripts/import-hugo-references.py; no inferred percentiles.\n'
                  'export const hugoSource = ' + json.dumps(source, ensure_ascii=False, indent=2) + ';\n')
print(f'{len(source["bases"]["new"])} contract price references; no percentile inference.')
