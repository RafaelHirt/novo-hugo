"""Import only approved SADT quantities from Manifestação GEC (5).

Usage: python scripts/import-production-sadt.py /path/to/workbook.xlsx
Reads cached values, validates financial formulas and green percentile cells.
Does not replace the original production/increment source files.
"""
import argparse
import hashlib
import json
import re
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import openpyxl

parser = argparse.ArgumentParser()
parser.add_argument('workbook')
args = parser.parse_args()
path = Path(args.workbook)
values = openpyxl.load_workbook(path, data_only=True)['HUGO - 1º TA']
formulas = openpyxl.load_workbook(path, data_only=False)[values.title]
assert [values[f'{column}3'].value for column in 'MNO'] == ['P25', 'P50', 'P75']
green = values['N6'].fill.fgColor
mapping = {
    38: 46, 39: 47, 40: 48, 41: 49, 42: 50, 43: 52, 44: 51,
    45: 53, 46: 54, 47: 55, 48: 56, 49: 58, 50: 59, 51: 60,
    52: 61, 53: 62, 54: 63, 55: 64, 56: 65,
    61: 69, 62: 72, 63: None, 64: 75, 65: 76, 66: 71,
}
root = Path(__file__).resolve().parents[1]
original_text = (root / 'production-increments-source.js').read_text()
original = json.loads(original_text.split('export const productionIncrementSource = ', 1)[1].rsplit(';', 1)[0])
original_rows = {row['id']: row for row in original['bases']['new']}


def cents(value):
    return int(Decimal(str(value)).quantize(Decimal('.01'), rounding=ROUND_HALF_UP) * 100)


rows, ignored_rows = [], []
for index, old_index in mapping.items():
    quantity_cell, amount_cell = f'J{index}', f'R{index}'
    formula = formulas[amount_cell].value.replace(' ', '').upper()
    match = re.fullmatch(rf'=ROUND\(J{index}\*([MNO]{index}),2\)', formula)
    assert match, (amount_cell, formula)
    unit_cell = match[1]
    selected = [f'{column}{index}' for column in 'MNO'
                if values[f'{column}{index}'].fill.patternType == 'solid'
                and values[f'{column}{index}'].fill.fgColor == green]
    assert selected == [unit_cell], (amount_cell, selected, unit_cell)
    quantity, unit = values[quantity_cell].value, values[unit_cell].value
    assert isinstance(quantity, int) and quantity >= 0
    assert cents(Decimal(str(quantity)) * Decimal(str(unit))) == cents(values[amount_cell].value)
    entry = {
        'name': values[f'C{index}'].value,
        'group': 'SADT interno' if index < 60 else 'SADT externo',
        'qty': quantity, 'unit': unit, 'unitBasis': {'M': 'P25', 'N': 'P50', 'O': 'P75'}[unit_cell[0]],
        'sourceQuantityCell': quantity_cell, 'sourceUnitCell': unit_cell,
        'sourceCell': amount_cell, 'sourceTotalCents': cents(values[amount_cell].value),
        'sourceFormula': formula,
    }
    if old_index is None:
        ignored_rows.append(entry)
        continue
    row_id = f'production-increment-new-{old_index}'
    assert row_id in original_rows
    assert unit == original_rows[row_id]['unit'], ('Quantity-only update changes price', row_id)
    rows.append({'id': row_id, **entry})
totals = {group: sum(row['sourceTotalCents'] for row in rows if row['group'] == group)
          for group in ['SADT interno', 'SADT externo']}
workbook_totals = {'SADT interno': cents(values['R57'].value), 'SADT externo': cents(values['R67'].value)}
for group, total in totals.items():
    assert total + sum(row['sourceTotalCents'] for row in ignored_rows if row['group'] == group) == workbook_totals[group]
payload = {
    'fileName': path.name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
    'sourceSheet': values.title, 'rows': rows,
    'ignoredRows': ignored_rows, 'groupTotalCents': totals, 'workbookGroupTotalCents': workbook_totals,
}
target = root / 'production-sadt-source.js'
target.write_text('// Approved SADT base quantities; generated by scripts/import-production-sadt.py.\n'
                  + 'export const productionSadtSource = ' + json.dumps(payload, ensure_ascii=False, indent=2) + ';\n')
print(f'{len(rows)} SADT rows checked against cached totals, formulas and selected green cells -> {target.name}')
